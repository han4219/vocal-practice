import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { extendManifest, hydrateCatalog } from '../src/lib/catalog.js';
const root = new URL('../', import.meta.url);
const data = new URL('src/data/', root);
const words = JSON.parse(await readFile(new URL('vocabulary.json', data), 'utf8'));
const definitions = JSON.parse(await readFile(new URL('course-definitions.json', data), 'utf8'));
let previous;
try { previous = JSON.parse(await readFile(new URL('course-groups.json', data), 'utf8')); } catch (error) { if (error.code !== 'ENOENT') throw error; }
const manifest = extendManifest(definitions, words, previous);
hydrateCatalog(words, manifest);
await writeFile(new URL('course-groups.json', data), JSON.stringify(manifest));
const payload = '{"version":1,"words":[\n' + words.map(w=>JSON.stringify(w)).join(',\n') + '\n],"courses":' + JSON.stringify(manifest.courses) + '}';
const delimiter = '$voca_catalog_data$';
if (payload.includes(delimiter)) throw new Error('Unexpected SQL delimiter in vocabulary.');
await mkdir(new URL('supabase/seeds/', root), { recursive: true });
await writeFile(new URL('supabase/seeds/003_catalog.sql', root), `-- Generated by npm run catalog:prepare. No private user progress is changed.\nbegin;\nselect public.voca_install_catalog(${delimiter}${payload}${delimiter}::jsonb);\ncommit;\n`);
console.log(`Prepared ${words.length} words, ${manifest.courses.length} courses, ${manifest.courses.reduce((n,c)=>n+c.groups.length,0)} fixed groups.`);
